    u_count=$(echo "$USERS_JSON" | jq 'length')
    local u=0
    while [ $u -lt "$u_count" ]; do
        local u_name u_org u_acct u_admin
        u_name=$(echo "$USERS_JSON" | jq -r ".[$u].username")
        u_org=$(echo "$USERS_JSON" | jq -r ".[$u].orgId // \"org1234567\"")
